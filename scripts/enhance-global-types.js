/**
 * This script enhances the global type definitions for dom-utils
 * It creates a comprehensive global declaration file by combining the ESM types
 */

const fs = require('fs');
const path = require('path');

// Paths to the type definition files
const esmTypesPath = path.resolve(__dirname, '../dist/types/dom-utils.d.ts');
const globalTypesPath = path.resolve(__dirname, '../dist/dom-utils.d.ts');

// Read the ESM type definitions
const esmTypes = fs.readFileSync(esmTypesPath, 'utf8');

// Create the global declaration file content
let globalContent = '// Generated by dom-utils build script\n\n';

// Extract function declarations from the ESM types
// Remove 'export declare' and keep the rest of each function declaration
const functionDeclarations = esmTypes
  .split('\n')
  .map(line => {
    if (line.startsWith('export declare ')) {
      return line.replace('export declare ', '');
    }
    return line;
  })
  .join('\n');

// Create the namespace declaration with the correct casing (DomUtils) to match Vite config
globalContent += `declare namespace DomUtils {\n${functionDeclarations}\n}\n\n`;
globalContent += 'export as namespace DomUtils;\n';
globalContent += 'export = DomUtils;\n';

// Write the global declaration file
fs.writeFileSync(globalTypesPath, globalContent, 'utf8');

console.log('✅ Created comprehensive global type definitions');
